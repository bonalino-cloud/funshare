// Списки слоя 4 (roast-engine §6). Конфиг, а не логика: правится без изменения кода проверки.
// Все строки в нижнем регистре и с «е» вместо «ё» (текст нормализуется так же, см. normalize.ts).
//
// Принцип списков: лучше потерять кандидата, чем пропустить красную линию (запасные кандидаты
// есть всегда), но частые безобидные слова не должны выпадать. Поэтому:
//  - `stems`  — слово НАЧИНАЕТСЯ с основы («толст» ловит «толстяк», «толстого»);
//  - `exact`  — слово равно одной из форм: для коротких и многозначных («вес» не «весна»,
//               «бог» не «богатый», «рак» не «рука», «семья» не «семь»);
//  - `except` — слова, начинающиеся с основы, но безобидные («толстовка», «трамплин»);
//  - `phrases` — фразы целыми словами.
// Каждая запись проверена тестом на безобидных соседях (output-check.test.ts).

export type Lexeme = {
  stems?: readonly string[];
  exact?: readonly string[];
  except?: readonly string[];
  phrases?: readonly string[];
};

