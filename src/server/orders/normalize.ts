/**
 * Кириллица, неотличимая на глаз от латиницы: человек с русской раскладкой набирает «FUN-АВС»
 * тем, что выглядит так же. Сводим к латинице; и `Ё` к `Е`. Нормализация одна и та же при создании
 * кода (админка) и при проверке, поэтому коллизии «разные коды → один» ловит уникальный индекс.
 */
const LOOKALIKES: Record<string, string> = {
  А: "A",
  В: "B",
  Е: "E",
  Ё: "E",
  К: "K",
  М: "M",
  Н: "H",
  О: "O",
  Р: "P",
  С: "C",
  Т: "T",
  Х: "X",
  У: "Y",
};

/**
 * Нормализованный код: NFKC, верхний регистр, только буквы и цифры (пробелы, дефисы, подчёркивания,
 * невидимые символы и знаки выкидываются), кириллические двойники → латиница. Цифру 0 и букву O
 * не склеиваем: случайные коды (`FUN-7K3Q-9XPA`) сами обходятся без путаных символов.
 * Пустой результат = не код.
 */
export function normalizePromoCode(input: string): string {
  let out = "";
  for (const ch of input.normalize("NFKC").toUpperCase()) {
    if (/[\p{L}\p{N}]/u.test(ch)) out += LOOKALIKES[ch] ?? ch;
  }
  return out;
}
